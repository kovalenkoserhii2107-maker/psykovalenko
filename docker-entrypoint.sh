#!/bin/sh
set -e

# Том Fly монтується в /data від імені root, а застосунок працює під
# nextjs (uid 1001) і сам теку в ньому створити не може: mkdir падає з
# EACCES, а з ним падало й збереження допису з обкладинкою.
# Тут ми ще root — створюємо теку, віддаємо її користувачу й лише потім
# скидаємо права.
if [ -n "$UPLOAD_DIR" ]; then
  mkdir -p "$UPLOAD_DIR"
  # Без -R: теки досить, файли в ній застосунок створює вже від себе,
  # а рекурсія на томі з тисячами вкладень сповільнювала б запуск.
  chown nextjs:nodejs "$UPLOAD_DIR"
fi

exec su-exec nextjs "$@"
