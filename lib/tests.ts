export const getTest = (slug: string) => TESTS.find((t) => t.slug === slug);

export const maxOption = (test: TestDefinition) =>
  Math.max(...test.options.map((o) => o.value));

export const maxScore = (test: TestDefinition) =>
  test.questions.length * maxOption(test);

export function interpret(test: TestDefinition, score: number) {
  if (!test.bands?.length) return '';
  return test.bands.find((b) => score <= b.upTo)?.label ?? test.bands.at(-1)!.label;
}

/** Бали за кожною шкалою профільного тесту. */
export function scaleScores(test: TestDefinition, answers: Record<string, number>) {
  if (!test.scales) return [];

  return test.scales.map((scale) => {
    const questions = test.questions.filter((q) => q.scale === scale.id);
    const value = questions.reduce((sum, q) => sum + (answers[q.id] ?? 0), 0);
    return {
      ...scale,
      value,
      max: questions.length * maxOption(test),
    };
  });
}
