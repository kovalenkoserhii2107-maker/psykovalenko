/**
 * Опитувальники для кабінету клієнта.
 *
 * УВАГА: формулювання пунктів і межі інтерпретації має звірити фахівчиня
 * з офіційним українським перекладом методики, перш ніж використовувати
 * результати в роботі. Це скринінг для розмови на сесії, а не діагноз.
 */

export type Option = { label: string; value: number; spoken: string[] };

export type Question = { id: string; text: string; scale?: string };

/** Шкала профільного тесту: результат — не одна цифра, а співвідношення. */
export type Scale = {
  id: string;
  short: string;
  name: string;
  description: string;
  /** Підказки фахівчині: про що варто розпитати. Клієнт їх не бачить. */
  hintHigh: string;
  hintLow: string;
};

export type TestDefinition = {
  slug: string;
  name: string;
  subtitle: string;
  intro: string;
  /** Спільний для всіх пунктів заголовок шкали. */
  scaleHint: string;
  options: Option[];
  questions: Question[];
  /** Відкрите питання в кінці — сюди зручно надиктувати голосом. */
  openQuestion: string;
  /** Для сумарних тестів: межі інтерпретації загального балу. */
  bands?: { upTo: number; label: string }[];
  /** Для профільних тестів: шкали, за якими розкладаються відповіді. */
  scales?: Scale[];
};

